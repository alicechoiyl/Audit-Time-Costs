function buildSectionsWithHours(hoursByCode: Record<string, number>): AuditSection[] {
  return createEmpty26Sections().map((sec) => ({
    ...sec,
    planned_hours: hoursByCode[sec.section_code] ?? 0,
  }));
}

function sumHours(sections: AuditSection[]): number {
  return Math.round(sections.reduce((acc, s) => acc + s.planned_hours, 0) * 10) / 10;
}

